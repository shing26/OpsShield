-- 事故外发 outbox（2026-11-27，ADR-0045；契约 plans/alert-push-accept.md）。
-- 设计约束：
--   ① 外发是**持久化待发事实**：请求线程/事务只写 outbox，不直接发 HTTP；
--      进程重启、队列满、上游 5xx 都不会让已发生的业务事件凭空消失。
--   ② 一个业务事件对同一频道只入一行：唯一键 (tenant, event_key, channel_id)，
--      冲突是重放，不是错误。created 用 "c:<incidentId>"，站内通知用 "n:<dedupe_key>"。
--   ③ 行内只存定位信息（事故 ID / 标题 / 优先级 / 时限 / 事件类型 / 负责人），
--      不复制 query、诊断正文、评论正文或引用片段。
--   ④ pending 行永不清理；sent/dead 由每日任务按留存天数有界删除。
-- 自增主键写 IDENTITY（同 V10/V11）：H2 PostgreSQL 兼容模式与 PostgreSQL 10+ 都成立。
CREATE TABLE IF NOT EXISTS incident_push_outbox (
    outbox_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant          VARCHAR(64)   NOT NULL,
    event_key       VARCHAR(200)  NOT NULL,
    incident_id     VARCHAR(64)   NOT NULL,
    kind            VARCHAR(32)   NOT NULL,
    recipient       VARCHAR(64)   NOT NULL DEFAULT '',
    priority        VARCHAR(8)    NOT NULL DEFAULT '',
    title           VARCHAR(120)  NOT NULL,
    due_at          TIMESTAMP     NULL,
    channel_id      VARCHAR(64)   NOT NULL,
    status          VARCHAR(16)   NOT NULL DEFAULT 'pending',
    attempts        INT           NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_attempt_at TIMESTAMP     NULL,
    last_status     INT           NULL,
    last_error      VARCHAR(500)  NULL,
    sent_at         TIMESTAMP     NULL,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_incident_push_outbox_event_channel
    ON incident_push_outbox(tenant, event_key, channel_id);
CREATE INDEX IF NOT EXISTS idx_incident_push_outbox_due
    ON incident_push_outbox(status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_incident_push_outbox_tenant_created
    ON incident_push_outbox(tenant, created_at);
